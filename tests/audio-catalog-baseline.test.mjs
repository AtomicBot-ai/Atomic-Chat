import assert from 'node:assert/strict'
import test from 'node:test'

import {
  audioCatalogBaseline,
  renderAudioCatalogModule,
} from '../scripts/sync-upstream-baseline.mjs'

const catalog = {
  $schema: './schema.audio.json',
  schema_version: 1,
  updated_at: '2026-11-01T20:00:00Z',
  models: [{ id: 'moss-tts-nano-100m' }],
}

test('the audio baseline is conf’s catalog minus $schema', () => {
  const { $schema: _schema, ...rest } = catalog

  assert.deepEqual(audioCatalogBaseline(catalog), rest)
})

test('an audio catalog with no version or no model is refused', () => {
  assert.throws(() => audioCatalogBaseline({ models: [{}] }), /schema_version/)
  assert.throws(
    () => audioCatalogBaseline({ schema_version: 1, models: [] }),
    /lists no models/
  )
})

test('the generated module says it is generated and holds the catalog', () => {
  const module = renderAudioCatalogModule(audioCatalogBaseline(catalog))

  assert.match(
    module,
    /^\/\/ GENERATED by scripts\/sync-upstream-baseline\.mjs/
  )
  assert.match(module, /export const BASELINE_AUDIO_CATALOG: unknown = \{/)
  assert.ok(module.includes('"moss-tts-nano-100m"'))
})
