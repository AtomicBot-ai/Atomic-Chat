import { invoke } from '@tauri-apps/api/core'

import { contextSupport, type ContextResizeMode } from '@/lib/context-support'
import type {
  CompactRequest,
  CompactResult,
  ContextMeasureRequest,
  ContextMeasureResult,
} from '@/lib/core-context-contract'

/**
 * The core's context routes for a local model session, through the Rust relay
 * (`atomic_core_call`): `context/measure` counts a chat request against the
 * window the session serves, `compact` summarizes the oldest turns of one.
 *
 * Both are new in the core. An older core answers them with a 404 — its own
 * control server says `INVALID_ARGUMENT` "No such control route", a body that
 * is not the core's envelope becomes `HTTP_404`: that is remembered for a while, so the chat
 * goes back to its own measuring and growth without asking again on every
 * turn. Any other failure only fails the one call.
 */

type Route = 'measure' | 'compact'

const ABSENT_CODES: ReadonlySet<string> = new Set([
  'HTTP_404',
  'NOT_FOUND',
  'ROUTE_NOT_FOUND',
])
/** How long an absent route is not asked again; the core may be replaced meanwhile. */
const ABSENT_TTL_MS = 10 * 60 * 1000
/** A measure the pre-flight waits for before it sends the request anyway. */
const MEASURE_TIMEOUT_MS = 5_000
/** A summary is generated by the model; this bounds a session that never answers. */
const COMPACT_TIMEOUT_MS = 180_000

const absentUntil: Record<Route, number> = { measure: 0, compact: 0 }

/** For tests. */
export function resetCoreContextRoutes(): void {
  absentUntil.measure = 0
  absentUntil.compact = 0
}

/** What the core's control server says for a path it has no route for. */
const NO_SUCH_ROUTE = /^No such control route\b/

/** Whether a relay rejection means the core has no such route. */
export function isRouteAbsentError(error: unknown): boolean {
  const { code, message } = (error ?? {}) as {
    code?: unknown
    message?: unknown
  }
  if (typeof code !== 'string') return false
  if (ABSENT_CODES.has(code)) return true
  return (
    code === 'INVALID_ARGUMENT' &&
    typeof message === 'string' &&
    NO_SUCH_ROUTE.test(message)
  )
}

/**
 * Whether the core answered `route` (both, when omitted) with a 404 lately:
 * it is a core older than history compaction.
 */
export function contextRoutesAbsent(route?: Route): boolean {
  const now = Date.now()
  if (route) return absentUntil[route] > now
  return absentUntil.measure > now || absentUntil.compact > now
}

function modelPath(providerId: string, modelId: string, suffix: string) {
  // Ids contain `/`; the core matches on the rest of the path, unencoded.
  return `/models/${providerId}/${modelId}/${suffix}`
}

class Timeout extends Error {}

async function coreCall<T>(
  route: Route,
  path: string,
  body: unknown,
  timeoutMs: number
): Promise<T> {
  let timer: ReturnType<typeof setTimeout> | undefined
  try {
    return await Promise.race([
      invoke<T>('atomic_core_call', { method: 'POST', path, body }),
      new Promise<never>((_, reject) => {
        timer = setTimeout(
          () => reject(new Timeout(`${route} timed out`)),
          timeoutMs
        )
      }),
    ])
  } catch (error) {
    if (isRouteAbsentError(error))
      absentUntil[route] = Date.now() + ABSENT_TTL_MS
    throw error
  } finally {
    if (timer) clearTimeout(timer)
  }
}

const RESIZE_MODES: ReadonlySet<string> = new Set([
  'reload',
  'restart',
  'fixed',
])

const positive = (value: unknown): number | undefined =>
  typeof value === 'number' && Number.isFinite(value) && value > 0
    ? Math.floor(value)
    : undefined

function readMeasure(raw: unknown): ContextMeasureResult | undefined {
  if (!raw || typeof raw !== 'object') return undefined
  const record = raw as Record<string, unknown>
  const promptTokens = record.promptTokens
  if (
    typeof promptTokens !== 'number' ||
    !Number.isFinite(promptTokens) ||
    promptTokens < 0
  ) {
    return undefined
  }
  if (typeof record.resize !== 'string' || !RESIZE_MODES.has(record.resize)) {
    return undefined
  }
  const windowTokens = positive(record.windowTokens)
  const maxWindowTokens = positive(record.maxWindowTokens)
  return {
    promptTokens: Math.ceil(promptTokens),
    exact: record.exact === true,
    ...(windowTokens !== undefined ? { windowTokens } : {}),
    ...(maxWindowTokens !== undefined ? { maxWindowTokens } : {}),
    resize: record.resize as ContextResizeMode,
    supportsPromptProgress: record.supportsPromptProgress === true,
  }
}

function readCompact(raw: unknown): CompactResult | undefined {
  if (!raw || typeof raw !== 'object') return undefined
  const record = raw as Record<string, unknown>
  if (typeof record.summary !== 'string' || !record.summary.trim()) {
    return undefined
  }
  if (
    typeof record.keepFrom !== 'number' ||
    !Number.isInteger(record.keepFrom) ||
    record.keepFrom < 0
  ) {
    return undefined
  }
  const count = (value: unknown) =>
    typeof value === 'number' && Number.isFinite(value) && value >= 0
      ? Math.floor(value)
      : 0
  return {
    summary: record.summary,
    keepFrom: record.keepFrom,
    summarizedCount: count(record.summarizedCount),
    tokensBefore: count(record.tokensBefore),
    tokensAfter: count(record.tokensAfter),
    cached: record.cached === true,
  }
}

/**
 * What `providerId`'s session counts for `request`, and the windows it is
 * measured against; `undefined` for a provider that is not a local engine, an
 * older core, no session, or any other failure — the caller then measures the
 * way it did before.
 */
export async function measureContext(
  providerId: string,
  modelId: string,
  request: ContextMeasureRequest
): Promise<ContextMeasureResult | undefined> {
  if (contextSupport(providerId).resize === undefined) return undefined
  if (contextRoutesAbsent('measure')) return undefined
  try {
    const raw = await coreCall<unknown>(
      'measure',
      modelPath(providerId, modelId, 'context/measure'),
      request,
      MEASURE_TIMEOUT_MS
    )
    return readMeasure(raw)
  } catch (error) {
    console.debug(
      `[context] measure unavailable for ${providerId}/${modelId}:`,
      error
    )
    return undefined
  }
}

export type CompactContextOutcome =
  | { ok: true; result: CompactResult }
  | {
      ok: false
      /** `absent` — an older core; `failed` — the summary could not be made. */
      reason: 'absent' | 'failed'
    }

/** Summarize the oldest turns of `request` with `providerId`'s loaded model. */
export async function compactContext(
  providerId: string,
  modelId: string,
  request: CompactRequest
): Promise<CompactContextOutcome> {
  if (contextSupport(providerId).resize === undefined) {
    return { ok: false, reason: 'absent' }
  }
  if (contextRoutesAbsent('compact')) return { ok: false, reason: 'absent' }
  try {
    const raw = await coreCall<unknown>(
      'compact',
      modelPath(providerId, modelId, 'compact'),
      request,
      COMPACT_TIMEOUT_MS
    )
    const result = readCompact(raw)
    if (!result) {
      console.warn(
        `[context] ${providerId}/${modelId} answered compact without a summary`,
        raw
      )
      return { ok: false, reason: 'failed' }
    }
    return { ok: true, result }
  } catch (error) {
    if (isRouteAbsentError(error)) return { ok: false, reason: 'absent' }
    console.warn(
      `[context] compact failed for ${providerId}/${modelId}:`,
      error
    )
    return { ok: false, reason: 'failed' }
  }
}
